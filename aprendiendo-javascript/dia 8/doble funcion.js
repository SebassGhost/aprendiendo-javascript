function sumar( a , b ) {
    return a + b;               // Multiplica los dos números y devuelve el resultado
}

function multiplicar(a, b){
    return a * b
}

let resultado = sumar(8, 2)
console.log("suma:", resultado)

let resultadoFinal = multiplicar(resultado , 5) //se crea la variable "resultadoFinal" para guardar la multiplicacion

console.log("multiplicacion:", resultadoFinal)